// The TV app: Free My TV's launcher (Java, still in ../app so ./build.sh and tools/check.sh keep working) plus the
// Room TV additions in Kotlin (tv/src/main/kotlin/io/freemytv/room): the LAN server, pairing and the Compose screens.
// Two generated inputs mirror what build.sh does by hand: Config.java from config.properties, and the manifest, which
// is app/AndroidManifest.xml with the Room components added (src/main/room-manifest.xml) and the `package` attribute
// removed (AGP 8 takes the namespace from here instead).
