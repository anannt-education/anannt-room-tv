val launcher = rootProject.file("app")

val generatedConfigDir = layout.buildDirectory.dir("generated/freemytv-config")
val generateConfig = tasks.register("generateFreeMyTvConfig") {
    description = "config.properties -> Config.java, as build.sh does"
    val example = rootProject.file("config.example.properties")
    val own = rootProject.file("config.properties")
    inputs.file(example)
    if (own.exists()) inputs.file(own)
    outputs.dir(generatedConfigDir)
    doLast {
        val props = Properties()
        (if (own.exists()) own else example).inputStream().use { props.load(it) }
        fun prop(key: String, fallback: String): String {
            val v = props.getProperty(key)?.trim()?.replace("\"", "") ?: ""
            return v.ifEmpty { fallback }
        }
        fun number(key: String, fallback: String): String {
            val v = prop(key, fallback)
            require(Regex("^-?[0-9]+(\\.[0-9]+)?$").matches(v)) { "config.properties: $key must be a number (got \"$v\")" }
            return v
        }
        fun flag(key: String, fallback: Boolean) = prop(key, fallback.toString()) == "true"
        val out = generatedConfigDir.get().file("io/freemytv/Config.java").asFile
        out.parentFile.mkdirs()
        out.writeText(
            """
            |package io.freemytv;
            |
            |/** Generated by tv/build.gradle.kts from config.properties: edit that file, not this one. */
            |final class Config {
            |    private Config() {}
            |
            |    static final String TMDB_KEY = "${prop("tmdb_key", "")}";
            |    static final String WATCHMODE_KEY = "${prop("watchmode_key", "")}";
            |    static final String TMDB_REGION = "${prop("tmdb_region", "US")}";
            |    static final String LATITUDE = "${number("latitude", "40.7128")}";
            |    static final String LONGITUDE = "${number("longitude", "-74.0060")}";
            |    static final String CITY = "${prop("city", "")}";
            |    static final String LANGUAGE = "${prop("language", "auto")}";
            |    static final String CURRENCY = "${prop("currency", "USD")}";
            |    static final String TEMPERATURE = "${prop("temperature", "auto")}";
            |    static final String HIDE_SERVICES = "${prop("hide_services", "")}";
            |    static final boolean DISABLE_ASSISTANT = ${flag("disable_assistant", false)};
            |    static final boolean SHOW_CRYPTO = ${flag("show_crypto", true)};
            |    static final boolean HIDE_ANIMATION = ${flag("hide_animation", false)};
            |}
            |""".trimMargin()
        )
    }
}

val generatedManifest = layout.buildDirectory.file("generated/freemytv-manifest/AndroidManifest.xml")
val generateManifest = tasks.register("generateRoomManifest") {
    description = "app/AndroidManifest.xml plus the Room TV components"
    val base = File(launcher, "AndroidManifest.xml")
    val extra = file("src/main/room-manifest.xml")
    inputs.files(base, extra)
    outputs.file(generatedManifest)
    doLast {
        val fragment = extra.readText()
        val permissions = fragment.substringAfter("<!-- permissions -->").substringBefore("<!-- /permissions -->")
        val components = fragment.substringAfter("<!-- components -->").substringBefore("<!-- /components -->")
        var text = base.readText()
        text = text.replace(Regex("""\s+package="io\.freemytv""""), "")
        text = text.replaceFirst("<application", "$permissions\n    <application")
        text = text.replaceFirst("</application>", "$components\n    </application>")
        val out = generatedManifest.get().asFile
        out.parentFile.mkdirs()
        out.writeText(text)
    }
}

